export const MERMAID_MESSAGES: Record<Lang, Record<MermaidKey, string>> = { es, en };

export type MermaidTranslate = (key: MermaidKey, params?: Record<string, string | number>) => string;

export const mermaidTranslator =
  (lang: Lang): MermaidTranslate =>
  (key, params = {}) =>
    MERMAID_MESSAGES[lang][key].replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
