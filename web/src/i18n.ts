export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { es, en };

export const isLang = (value: unknown): value is Lang => (LANGS as readonly unknown[]).includes(value);

export function resolveLang(query: string, saved: string | null): Lang {
  const asked = new URLSearchParams(query).get("lang");
  return isLang(asked) ? asked : isLang(saved) ? saved : DEFAULT_LANG;
}

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export const translator =
  (lang: Lang): Translate =>
  (key, params = {}) =>
    MESSAGES[lang][key].replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
