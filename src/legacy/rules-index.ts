import path from "node:path";
import { relativeLink } from "../docs/files.js";
import type { Lang } from "../i18n/index.js";
import { evidenceOf, listField, type Legacy, type LegacyItem } from "./load.js";
import { RULE_STATUSES } from "./model.js";

const TEXT = {
  es: {
    title: "Índice de reglas de negocio",
    generated: "Archivo generado por `engkit index`. No lo edites: se sobrescribe cada vez. Para cambiarlo, edita las reglas y vuelve a ejecutar el comando.",
    headers: ["ID", "Título", "Área", "Estado", "Evidencias", "Pruebas", "Defectos", "Preguntas abiertas", "Responsable"],
    empty: "Todavía no hay reglas. Crea una con `engkit new rn \"<título>\"`.",
    total: "Total",
  },
  en: {
    title: "Business rule index",
    generated: "File generated by `engkit index`. Do not edit it: it is overwritten every time. To change it, edit the rules and run the command again.",
    headers: ["ID", "Title", "Area", "Status", "Evidence", "Tests", "Defects", "Open questions", "Owner"],
    empty: "There are no rules yet. Create one with `engkit new rn \"<title>\"`.",
    total: "Total",
  },
} as const;

const cell = (v: unknown) => String(v ?? "").trim().replace(/\r?\n/g, " ").replace(/\|/g, "\\|");

/**
 * The generated rule index. It only uses the project's own documents, never the evidence roots, so every
 * machine produces the same text.
 */
export function generateRulesIndex(lang: Lang, legacy: Legacy, openQuestions: Set<string>, date: string): string {
  const text = TEXT[lang];
  const file = legacy.paths.rulesIndex;
  const link = (item: LegacyItem) => `[${item.id}](${relativeLink(file, item.file)})`;
  const pointing = (items: LegacyItem[], id: string) =>
    items.filter((i) => listField(i, "rules")?.includes(id)).map(link).join(", ");

  const area = (r: LegacyItem) => cell(r.fm?.data["area"]);
  const rules = [...legacy.items.rule].sort((a, b) => {
    const [x, y] = [area(a), area(b)];
    return x < y ? -1 : x > y ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
  });

  const lines = [
    "---",
    "id: RULES-INDEX",
    "generated: true",
    `date: ${date}`,
    "---",
    "",
    `<!-- ${text.generated} -->`,
    "",
    `# ${text.title}`,
    "",
    `> ${text.generated}`,
    "",
  ];
  if (rules.length === 0) {
    lines.push(text.empty, "");
    return lines.join("\n");
  }

  const counts = RULE_STATUSES.map((s) => [s, rules.filter((r) => r.fm?.data["status"] === s).length] as const)
    .filter(([, n]) => n > 0)
    .map(([s, n]) => `${s}: ${n}`);
  lines.push(`${text.total}: ${rules.length} (${counts.join(", ")})`, "");
  lines.push(`| ${text.headers.join(" | ")} |`, `|${text.headers.map(() => "---").join("|")}|`);
  for (const rule of rules) {
    const data = rule.fm?.data ?? {};
    const adr = data["status"] === "modified" && data["decision"] ? ` (${cell(data["decision"])})` : "";
    const questions = (listField(rule, "questions") ?? []).filter((q) => openQuestions.has(q));
    const row = [
      link(rule),
      cell(rule.title),
      area(rule),
      `${cell(data["status"])}${adr}`,
      String(evidenceOf(rule)?.length ?? 0),
      pointing(legacy.items.test, rule.id),
      pointing(legacy.items.defect, rule.id),
      cell(questions.join(", ")),
      cell(data["owner"]),
    ];
    lines.push(`| ${row.join(" | ")} |`);
  }
  lines.push("");
  return lines.join("\n");
}

export const rulesIndexPath = (cwd: string, legacy: Legacy) => path.join(cwd, legacy.paths.rulesIndex);
