import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { loadConfig } from "../config.js";
import { slugify } from "../docs/adr.js";
import { todayISO } from "../docs/context.js";
import { serializeAnswers } from "./answers.js";
import type { PromptAnswers } from "./model.js";

export const DEFAULT_PROMPTS_DIR = "prompts";

export interface SaveOptions {
  cwd: string;
  /** Name given to `--save <name>`; defaults to the goal. */
  name?: string | undefined;
  /** Add the prompts folder to .gitignore when it is not ignored yet (default true). */
  gitignore?: boolean;
  today?: string;
}

export interface SaveResult {
  markdownFile: string;
  answersFile: string;
  /** Set when .gitignore was changed. */
  gitignoreUpdated: boolean;
  /** Set when the folder is inside a git repo and not ignored (only with gitignore: false). */
  notIgnored: boolean;
}

function git(cwd: string, args: string[]): { ok: boolean; code: number } {
  try {
    execFileSync("git", ["-C", cwd, ...args], { stdio: "ignore" });
    return { ok: true, code: 0 };
  } catch (e) {
    const status = (e as { status?: number }).status;
    return { ok: false, code: typeof status === "number" ? status : 128 };
  }
}

/** Ignores the prompts folder in a git repo. Returns whether it is ignored afterwards and whether .gitignore changed. */
function ensureIgnored(cwd: string, dir: string, update: boolean): { updated: boolean; ignored: boolean } {
  if (!git(cwd, ["rev-parse", "--is-inside-work-tree"]).ok) return { updated: false, ignored: true };
  if (git(cwd, ["check-ignore", "-q", `${dir}/x.md`]).ok) return { updated: false, ignored: true };
  if (!update) return { updated: false, ignored: false };

  const file = path.join(cwd, ".gitignore");
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf-8") : "";
  const prefix = current === "" || current.endsWith("\n") ? "" : "\n";
  fs.writeFileSync(file, `${current}${prefix}\n# Prompts generated by engkit (may contain internal context)\n${dir}/\n`, "utf-8");
  return { updated: true, ignored: true };
}

/** Writes `<dir>/<date>-<name>.md` and the `.yaml` answers next to it, never overwriting an existing file. */
export function savePrompt(markdown: string, answers: PromptAnswers, options: SaveOptions): SaveResult {
  const dir = loadConfig(options.cwd).promptsDir ?? DEFAULT_PROMPTS_DIR;
  const date = options.today ?? todayISO();
  const slug = slugify(options.name ?? answers.goal ?? "") || "prompt";

  const abs = path.join(options.cwd, dir);
  fs.mkdirSync(abs, { recursive: true });
  let base = `${date}-${slug}`;
  for (let n = 2; fs.existsSync(path.join(abs, `${base}.md`)) || fs.existsSync(path.join(abs, `${base}.yaml`)); n++) {
    base = `${date}-${slug}-${n}`;
  }

  const markdownFile = path.posix.join(dir, `${base}.md`);
  const answersFile = path.posix.join(dir, `${base}.yaml`);
  fs.writeFileSync(path.join(options.cwd, markdownFile), markdown, { encoding: "utf-8", flag: "wx" });
  fs.writeFileSync(path.join(options.cwd, answersFile), serializeAnswers(answers), { encoding: "utf-8", flag: "wx" });

  const ig = ensureIgnored(options.cwd, dir, options.gitignore !== false);
  return { markdownFile, answersFile, gitignoreUpdated: ig.updated, notIgnored: !ig.ignored };
}
