import fs from "node:fs";
import path from "node:path";
import { docPath, loadConfig } from "../config.js";
import { todayISO, type DocOptions } from "../docs/context.js";
import { listAdrs, type AdrEntry } from "../docs/adr.js";
import { relativeLink, type DocPaths } from "../docs/files.js";

type IndexPaths = Pick<DocPaths, "adrDir" | "decisions">;
import type { Lang } from "../i18n/index.js";

const TEXT = {
  es: {
    title: "Índice de decisiones",
    generated: "Archivo generado por `engkit index`. No lo edites: se sobrescribe cada vez. Para cambiarlo, edita los ADR y vuelve a ejecutar el comando.",
    headers: ["Número", "Título", "Estado", "Fecha", "Reemplaza", "Reemplazado por"],
    empty: "Todavía no hay ADR. Crea uno con `engkit new adr \"<título>\"`.",
  },
  en: {
    title: "Decision index",
    generated: "File generated by `engkit index`. Do not edit it: it is overwritten every time. To change it, edit the ADRs and run the command again.",
    headers: ["Number", "Title", "Status", "Date", "Supersedes", "Superseded by"],
    empty: "There are no ADRs yet. Create one with `engkit new adr \"<title>\"`.",
  },
} as const;

const escapeCell = (s: string) => s.replace(/\|/g, "\\|");

/** Builds the DECISIONS index. `supersededBy` also comes from other ADRs that declare `supersedes`. */
export function generateIndex(lang: Lang, adrDirAbs: string, paths: IndexPaths, date: string): string {
  const text = TEXT[lang];
  const { adrs, warnings } = listAdrs(adrDirAbs);
  for (const w of warnings) console.error(`warning: ${w}`);

  const reverse = new Map<string, string>();
  for (const adr of adrs) if (adr.supersedes) reverse.set(adr.supersedes, adr.id);

  const link = (adr: AdrEntry) => {
    const target = path.posix.join(paths.adrDir, adr.file);
    return `[${adr.id}](${relativeLink(paths.decisions, target)})`;
  };

  const lines = [
    "---",
    "id: DECISIONS",
    "generated: true",
    `date: ${date}`,
    "---",
    "",
    `<!-- ${text.generated} -->`,
    "",
    `# ${text.title}`,
    "",
    `> ${text.generated}`,
    "",
  ];

  if (adrs.length === 0) {
    lines.push(text.empty, "");
  } else {
    lines.push(`| ${text.headers.join(" | ")} |`, `|${text.headers.map(() => "---").join("|")}|`);
    for (const adr of adrs) {
      const supersededBy = adr.supersededBy ?? reverse.get(adr.id) ?? "";
      lines.push(
        `| ${link(adr)} | ${escapeCell(adr.title)} | ${adr.status} | ${adr.date} | ${adr.supersedes ?? ""} | ${supersededBy} |`
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** `engkit index`: regenerates the ADR index. Returns the file written. */
export function runIndex(lang: Lang, options: DocOptions = {}): string {
  const cwd = options.cwd ?? process.cwd();
  const config = loadConfig(cwd);
  const paths: IndexPaths = { adrDir: docPath(config, "adrDir"), decisions: docPath(config, "decisions") };
  const content = generateIndex(lang, path.join(cwd, paths.adrDir), paths, options.today ?? todayISO());
  const out = path.join(cwd, paths.decisions);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, content, "utf-8");
  console.log(`generated  ${paths.decisions}`);
  return paths.decisions;
}
